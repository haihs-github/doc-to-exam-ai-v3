// School class (many teachers, no owner): school year, system-wide unique code via codeKey/activeCodeKey, invite tokens, soft delete. Port of server/models/Class.js.
import mongoose, { Schema, type Model, type Types } from 'mongoose';
import { toUpperVi } from '../lib/vnText';
import { softDeletePlugin, type ISoftDelete, type ISoftDeleteMethods } from './plugins/softDelete';

export interface IInviteSide {
  token?: string; // select:false; generated by the invite service (Task 4), not here
  enabled: boolean;
  rotatedAt: Date;
}
export interface IClass extends ISoftDelete {
  createdBy: Types.ObjectId;
  name: string;
  code: string;
  codeKey: string;
  activeCodeKey?: string;
  startYear: number;
  endYear: number;
  status: 'active' | 'graduated';
  invite: { student: IInviteSide; teacher: IInviteSide };
  createdAt: Date;
  updatedAt: Date;
}
type ClassModelType = Model<IClass, object, ISoftDeleteMethods> & {
  /** One atomic pipeline update; optional new code. Code taken by a live class -> E11000, class stays deleted. */
  restoreWithCode(
    id: Types.ObjectId | string,
    opts?: { code?: string },
  ): ReturnType<Model<IClass>['updateOne']>;
};

const inviteSide = () => ({
  token: { type: String, select: false }, // plaintext (decision Q4); only the invite endpoint returns it
  enabled: { type: Boolean, default: true },
  rotatedAt: { type: Date, default: Date.now },
});
const isInt = { validator: Number.isInteger, message: 'Niên khóa phải là số nguyên.' };
const codeKeyOf = (code: string): string => code.normalize('NFC').trim().toLocaleLowerCase('vi');

// Tokens must never leak: strip them from any serialisation even if selected.
const hideTokens = (_doc: unknown, ret: Record<string, unknown>): Record<string, unknown> => {
  const invite = ret.invite as Record<string, Record<string, unknown>> | undefined;
  if (invite)
    for (const side of ['student', 'teacher']) if (invite[side]) delete invite[side].token;
  return ret;
};

const ClassSchema = new Schema<IClass, ClassModelType, ISoftDeleteMethods>(
  {
    createdBy: { type: Schema.Types.ObjectId, ref: 'User', required: true }, // record only, NOT for authorisation
    name: {
      type: String,
      required: [true, 'Tên lớp là bắt buộc.'],
      trim: true,
      maxlength: [100, 'Tên lớp tối đa 100 ký tự.'],
    },
    code: {
      type: String,
      required: [true, 'Mã lớp là bắt buộc.'],
      trim: true,
      maxlength: [30, 'Mã lớp tối đa 30 ký tự.'],
    },
    codeKey: { type: String, required: true }, // NFC + trim + lowercase vi; always derived from code
    activeCodeKey: { type: String }, // only while not deleted: a deleted class releases its code (partial unique below)
    startYear: {
      type: Number,
      required: [true, 'Năm bắt đầu là bắt buộc.'],
      min: [2000, 'Năm bắt đầu từ 2000 đến 2100.'],
      max: [2100, 'Năm bắt đầu từ 2000 đến 2100.'],
      validate: isInt,
    },
    endYear: {
      type: Number,
      required: [true, 'Năm kết thúc là bắt buộc.'],
      min: [2000, 'Năm kết thúc từ 2000 đến 2112.'],
      max: [2112, 'Năm kết thúc từ 2000 đến 2112.'],
      validate: isInt,
    },
    status: {
      type: String,
      enum: {
        values: ['active', 'graduated'],
        message: 'Trạng thái chỉ là active hoặc graduated.',
      },
      default: 'active',
    },
    invite: { student: inviteSide(), teacher: inviteSide() },
  },
  { timestamps: true, toObject: { transform: hideTokens }, toJSON: { transform: hideTokens } },
);

ClassSchema.plugin(softDeletePlugin);

// Delete must $unset activeCodeKey (partial {$exists:true} still matches null, so $set null would keep the code taken).
ClassSchema.methods.softDelete = function softDeleteClass(this: {
  _id: Types.ObjectId;
  constructor: unknown;
}) {
  return (this.constructor as Model<IClass>).updateOne(
    { _id: this._id },
    [{ $set: { deletedAt: new Date() } }, { $unset: 'activeCodeKey' }],
    { updatePipeline: true },
  ); // Mongoose 9 refuses pipeline updates without this option
};

ClassSchema.statics.restoreWithCode = function restoreWithCode(
  this: Model<IClass>,
  id: Types.ObjectId | string,
  { code }: { code?: string } = {},
) {
  const newCode = typeof code === 'string' ? toUpperVi(code) : '';
  if (typeof code === 'string' && (!newCode || newCode.length > 30))
    throw new Error(newCode ? 'Mã lớp tối đa 30 ký tự.' : 'Mã lớp là bắt buộc.');
  // $literal: a code starting with `$` would otherwise be read as a field path
  const rename = newCode
    ? { code: { $literal: newCode }, codeKey: { $literal: codeKeyOf(newCode) } }
    : {};
  return this.updateOne(
    { _id: id, deletedAt: { $ne: null } },
    [{ $set: { deletedAt: null, ...rename } }, { $set: { activeCodeKey: '$codeKey' } }],
    { updatePipeline: true },
  ).setOptions({ withDeleted: true });
};

// Inherited restore() would bring deletedAt back without activeCodeKey (code uniqueness lost): route through restoreWithCode.
ClassSchema.methods.restore = function restoreClass(this: {
  _id: Types.ObjectId;
  constructor: unknown;
}) {
  return (this.constructor as ClassModelType).restoreWithCode(this._id);
};

ClassSchema.pre('validate', function deriveAndCheck() {
  if (typeof this.name === 'string') this.name = toUpperVi(this.name);
  if (typeof this.code === 'string') {
    this.code = toUpperVi(this.code);
    this.codeKey = codeKeyOf(this.code);
  }
  this.activeCodeKey = this.deletedAt ? undefined : this.codeKey;
  const span = this.endYear - this.startYear;
  if (Number.isInteger(span) && (span < 1 || span > 12))
    this.invalidate('endYear', 'Niên khóa phải kéo dài từ 1 đến 12 năm.');
});

ClassSchema.index(
  { activeCodeKey: 1 },
  { unique: true, partialFilterExpression: { activeCodeKey: { $exists: true } } },
);
ClassSchema.index({ 'invite.student.token': 1 }, { unique: true, sparse: true });
ClassSchema.index({ 'invite.teacher.token': 1 }, { unique: true, sparse: true });

export const ClassModel: ClassModelType =
  (mongoose.models.Class as ClassModelType | undefined) ??
  mongoose.model<IClass, ClassModelType>('Class', ClassSchema);
